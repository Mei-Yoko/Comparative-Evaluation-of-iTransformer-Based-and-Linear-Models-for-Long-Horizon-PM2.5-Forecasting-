import pandas as pd
import numpy as np


files = ['2021.xlsx', '2022.xlsx', '2023.xlsx', '2024.xlsx', '2025.xlsx']
dfs = []

for f in files:
    xls = pd.ExcelFile(f)
    df = pd.read_excel(f, sheet_name=xls.sheet_names[0])
    df['Date'] = pd.to_datetime(df['Date'], errors='coerce')
    dfs.append(df)

full_df = pd.concat(dfs, ignore_index=True).dropna(subset=['Date'])
full_df = full_df.groupby('Date', as_index=False).mean()
full_df = full_df.set_index('Date').resample('D').mean()

# 5 station
station_cols = [c for c in full_df.columns if c != 'Date'][:5]
full_df[station_cols] = full_df[station_cols].apply(pd.to_numeric, errors='coerce')

# DATA CLEANING & OUTLIER TREATMENT
for col in station_cols:

    full_df.loc[full_df[col] <= 0, col] = np.nan
    upper_limit = full_df[col].quantile(0.995)
    full_df.loc[full_df[col] > upper_limit, col] = upper_limit

# 3. Interpolate Clean
full_df[station_cols] = full_df[station_cols].interpolate(method='time').bfill().ffill()

print(f"ใช้ 5 ตัวแปร (สถานี): {station_cols}")
print(f"Data Cleaning Completed! Shape: {full_df[station_cols].shape}")

import torch

# 5 varible (M=5)
SEQ_LEN = 60
PRED_LEN = 30
DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

data_m5 = full_df[station_cols].values.astype(np.float32)

X, Y = [], []
for i in range(len(data_m5) - SEQ_LEN - PRED_LEN + 1):
    X.append(data_m5[i : i + SEQ_LEN, :])
    Y.append(data_m5[i + SEQ_LEN : i + SEQ_LEN + PRED_LEN, :])

X = np.array(X, dtype=np.float32)
Y = np.array(Y, dtype=np.float32)

split = int(len(X) * 0.8)
X_train, Y_train = X[:split], Y[:split]
X_test, Y_test = X[split:], Y[split:]

print(f"X_train shape: {X_train.shape}, Y_train shape: {Y_train.shape}")
print(f"X_test shape:  {X_test.shape},  Y_test shape:  {Y_test.shape}")

import matplotlib.pyplot as plt
import forecast2win.metrics as M
from forecast2win.models import get_model

# build iTransformer
model_mse = get_model(
    "itransformer",
    seq_len=SEQ_LEN,
    pred_len=PRED_LEN,
    n_channels=5,
    d_model=64,
    e_layers=2,
    dropout=0.1
)

# train( MSE Loss)
model_mse.fit(
    X_train,
    y=Y_train,
    loss="mse",
    epochs=40,
    batch_size=32,
    scale=True,
    device=DEVICE,
    lr=1e-3,
    weight_decay=1e-5
)

pred_mse = model_mse.predict(X_test)
print(" [Tuned iTransformer MSE M=5] Train & Predict Completed!")

# Actual vs Prediction (MSE)
test_dates = full_df.index[-len(Y_test):]
target_station_idx = 0
station_name = station_cols[target_station_idx]

actual_values = Y_test[:, 0, target_station_idx]
pred_values = pred_mse[:, 0, target_station_idx]

plt.figure(figsize=(14, 6))
plt.plot(test_dates, actual_values, label=f'Actual PM2.5 ({station_name})', color='black', linewidth=1.5, alpha=0.85)
plt.plot(test_dates, pred_values, label=f'Tuned iTransformer (MSE Loss) M=5', color='#d62728', linewidth=1.5, linestyle='--')

plt.title(f'Tuned iTransformer MSE (M=5) PM2.5 Forecast vs Actual: {station_name}', fontsize=14, fontweight='bold')
plt.xlabel('Date', fontsize=12)
plt.ylabel('PM2.5 Concentration (µg/m³)', fontsize=12)
plt.grid(True, linestyle=':', alpha=0.6)
plt.legend(fontsize=11)
plt.tight_layout()

plt.savefig('itransformer_m5_mse_result.png', dpi=300)
plt.show()

